test('salvamento v2 migra para v3 sem perder peixes e dinheiro',function()
 local g=Game.new(18)
 local state=JSON.decode(JSON.encode(g.s))
 state.version=2;state.magic={['1']=true}
 local restored,err=Game.fromTable(state);assert(restored,err)
 eq(restored.s.version,9);eq(#restored.s.tanks.main,4)
 eq(restored.s.cash,200)
 assert(restored.s.prototype_magic['1'])
 assert(not restored.s.magic['1'])
end)
print('\n'..okCount..' testes passaram.')
