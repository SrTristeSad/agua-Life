-- Execute na raiz: texlua tests/run.lua  (ou: lua tests/run.lua)
package.path='./?.lua;./?/init.lua;'..package.path
local Game=require('core.game')
local JSON=require('core.json')
local C=require('core.config')
local okCount=0
local function test(name,fn)
 local ok,err=pcall(fn)
 if not ok then io.stderr:write('FALHOU '..name..': '..tostring(err)..'\n');os.exit(1) end
 okCount=okCount+1; print('OK',name)
end
local function eq(a,b) assert(a==b,tostring(a)..' != '..tostring(b)) end
local function adult(g) return g:addFish('main',1,1,20) end

test('dois adultos e dois jovens iniciais',function()
 local g=Game.new(1);eq(#g.s.tanks.main,4);eq(g.s.cash,200)
 eq(g:fishStage(g.s.tanks.main[1]),'Adulto')
 eq(g:fishStage(g.s.tanks.main[4]),'Filhote')
end)
test('ciclo de vida 6 e 20',function()
 local g=Game.new(1);local f=g.s.tanks.main[4]
 f.age=5;eq(g:fishStage(f),'Filhote');f.age=6;eq(g:fishStage(f),'Jovem')
 f.age=20;eq(g:fishStage(f),'Adulto')
end)
test('passagem de tempo e fracao conservada',function()
 local g=Game.new(1);g:advance(C.YEAR*.6);eq(g.s.tanks.main[1].age,20)
 g:advance(C.YEAR*.4);eq(g.s.tanks.main[1].age,21)
 eq(g.s.tanks.main[1].fed,99)
end)
test('sem parceiro nao reproduz',function()
 local g=Game.new(1);local f=g.s.tanks.main[1]
 assert(g:move(f.id,'isolation'))
 assert(not g:breed())
end)
test('pares jovens nao reproduzem',function()
 local g=Game.new(1)
 local young=g.s.tanks.main[3].id;local baby=g.s.tanks.main[4].id
 assert(g:move(young,'isolation'))
 assert(g:move(baby,'isolation'))
 assert(not g:breed())
end)
test('par de adultos pode reproduzir com isolamento cheio',function()
 local g=Game.new(1)
 assert(g:move(g.s.tanks.main[1].id,'isolation'))
 assert(g:move(g.s.tanks.main[1].id,'isolation'))
 assert(g:breed());assert(g.s.tanks.isolation[1].eggs_at)
 assert(not g:breed())
end)
test('eclosao apos quatro ciclos de crescimento',function()
 local g=Game.new(1)
 assert(g:move(g.s.tanks.main[1].id,'isolation'))
 assert(g:move(g.s.tanks.main[1].id,'isolation'))
 assert(g:breed())
 g:advance(C.YEAR*4-1);eq(#g.s.tanks.main,2)
 g:advance(1);assert(#g.s.tanks.main>=3)
 eq(g.s.tanks.isolation[1].eggs_at,false)
end)
test('tanque cheio impede mover ou adicionar',function()
 local g=Game.new(1)
 for _=5,C.CAPACITY.main do g:addFish('main',1,1,0) end
 eq(#g.s.tanks.main,C.CAPACITY.main)
 assert(not g:addFish('main',1,1,0))
end)
test('so adulto pode ir para venda',function()
 local g=Game.new(1)
 local child=g.s.tanks.main[4]
 assert(not g:move(child.id,'sale'))
 assert(g:move(g.s.tanks.main[1].id,'sale'))
end)
test('venda adiciona dinheiro e atualiza estatisticas',function()
 local g=Game.new(1)
 assert(g:move(g.s.tanks.main[1].id,'sale'))
 local fish=g.s.tanks.sale[1]
 local value=fish.price
 local success,amount=g:sell(fish.id)
 assert(success);eq(amount,value);eq(g.s.cash,200+value);eq(g.s.stats.sold,1)
end)
test('fome e saude',function()
 local g=Game.new(1)
 local f=g.s.tanks.main[1]
 f.fed=0;g:advance(C.YEAR);assert(f.health<100)
end)
test('alimentacao consome estoque e aumenta saciedade',function()
 local g=Game.new(1);local f=g.s.tanks.main[1];f.fed=35
 assert(g:feed(f.id));eq(g.s.supplies.food,4);eq(f.fed,85)
end)
test('compras debita e adiciona recursos',function()
 local g=Game.new(1)
 assert(g:purchase('food'));eq(g.s.cash,180);eq(g.s.supplies.food,10)
end)
test('tratamento respeita doenca',function()
 local g=Game.new(1);local f=g.s.tanks.main[1]
 f.disease='ick';g.s.supplies.ick=1
 assert(not g:medicine(f.id,'fungus'))
 g.int=function() return 0 end -- fixa sorteio do tratamento em sucesso (0<40)
 assert(g:medicine(f.id,'ick'));eq(f.disease,false);eq(g.s.stats.healed,1)
end)
test('pesquisa inicia e termina',function()
 local g=Game.new(1)
 assert(g:startResearch('food'));eq(g.s.cash,110)
 assert(not g:startResearch('environment'))
 g:advance(C.RESEARCH_SECONDS[1]);eq(g.s.research.food,1)
 eq(g.s.research_job,false)
end)
test('loja fecha e abre para vendas automaticas',function()
 local g=Game.new(1)
 assert(g:move(g.s.tanks.main[1].id,'sale'))
 g.s.sale_open=false;g:advance(C.YEAR)
 eq(g.s.stats.sold,0)
end)
test('equipamento e segundo tanque podem ser desbloqueados',function()
 local g=Game.new(1);g.s.cash=600
 assert(g:purchase('second'));eq(g.s.unlocked.second,true)
 assert(not g:purchase('second'))
 assert(g:move(g.s.tanks.main[1].id,'second'))
end)
test('tempo offline limita a 24 horas e nao aplica velocidade',function()
 local g=Game.new(1)
 g.s.game_speed=20;g.s.wall=1000
 eq(g:offline(1000+C.MAX_OFFLINE*5),C.MAX_OFFLINE)
 eq(g.s.time,C.MAX_OFFLINE)
end)
test('geracao deterministica',function()
