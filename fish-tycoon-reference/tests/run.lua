end)
test('genetica gera alelos validos',function()
 local g=Game.new(1)
 for _=1,100 do
  local dna,body,tail=g:inherit({body={1,2},tail={2,3}},{body={4,5},tail={5,6}})
  assert(body>=1 and body<=21 and tail>=1 and tail<=21)
  eq(#dna.body,2);eq(#dna.tail,2)
 end
end)
test('roundtrip JSON e salvamento carregavel',function()
 local g=Game.new(1);assert(g:move(g.s.tanks.main[1].id,'isolation'))
 local encoded=JSON.encode(g.s)
 local decoded=JSON.decode(encoded)
 local restored,err=Game.fromTable(decoded)
 assert(restored,err);eq(restored.s.next_id,g.s.next_id)
 eq(restored.s.tanks.isolation[1].id,g.s.tanks.isolation[1].id)
 assert(JSON.decode(JSON.encode({text='teste \"escape\"',x=true})).x)
end)
test('salvamento corrompido e rejeitado',function()
 local result=pcall(JSON.decode,'{"break":1,')
 assert(not result)
 assert(not Game.fromTable({version=1}))
end)
test('sete descobertas magicas identificaveis',function()
 local g=Game.new(1);g.s.tanks.main={}
 local catalog=require('core.catalog')
 for i,m in ipairs(catalog.magic) do
  g:addFish('main',m.body,m.tail,20)
 end
 eq(g:countMagic(),7)
end)

test('matriz de precos J2ME 21x21 com 13 substituicoes',function()
 local jar=require('core.jar_data')
 assert(#jar.bodyValues==21 and #jar.finValues==21)
 eq(jar.basePrice(1,1),4)
 eq(jar.basePrice(8,8),190)
 eq(jar.basePrice(9,9),20)
 eq(jar.basePrice(11,10),70)
 eq(jar.basePrice(21,17),48)
 eq(jar.basePrice(15,15),55)
 eq(jar.basePrice(12,12),70)
 eq(jar.basePrice(14,7),95)
 local overridden=0
 for _,line in pairs(jar.overrides) do for _ in pairs(line) do overridden=overridden+1 end end
 eq(overridden,13)
 for i=1,21 do for j=1,21 do assert(jar.basePrice(i,j)>=0) end end
end)
