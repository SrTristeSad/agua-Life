package.path='./?.lua;./?/init.lua;'..package.path
local Game=require('core.game')
local Config=require('core.config')
local JSON=require('core.json')
local Catalog=require('core.catalog')
local Atlas=require('core.atlas')
local count=0
local function test(name,fn)
 local ok,err=pcall(fn)
 if not ok then error(name..': '..tostring(err)) end
 count=count+1;print('OK - '..name)
end
local function eq(a,b) assert(a==b,tostring(a)..' != '..tostring(b)) end

test('crescimento padrao em 10 minutos e 1 segundo parcial',function()
 local g=Game.new(2)
 eq(g.s.version,9)
 g:advance(599)
 eq(g.s.tanks.main[1].age,20)
 eq(g.s.growth_elapsed,599)
 g:advance(1)
 eq(g.s.tanks.main[1].age,21)
 eq(g.s.growth_elapsed,0)
end)
test('troca de velocidade preserva a proporcao do ciclo parcial',function()
 local g=Game.new(2)
 g:advance(300)
 eq(g.s.growth_elapsed,300)
 assert(g:setGrowthMinutes(15))
 eq(g.s.growth_elapsed,450)
 g:advance(449)
 eq(g.s.tanks.main[1].age,20)
 g:advance(1)
 eq(g.s.tanks.main[1].age,21)
 assert(g:setGrowthMinutes(5))
 g:advance(300)
 eq(g.s.tanks.main[1].age,22)
 assert(not g:setGrowthMinutes(1))
end)
test('media inteira dos indices parentais do JAR',function()
 local g=Game.new(3)
 g.s.magic={}
 local MUTATION=Config.MUTATION
 Config.MUTATION=0
 local trace,b,t=g:combineParents(1,8,20,21)
 Config.MUTATION=MUTATION
 eq(b,10)
 eq(t,14)
 eq(trace.body[1],1)
 eq(trace.body[2],20)
 eq(trace.mutated,false)
end)
test('dois adultos podem cruzar independentemente de sexos experimentais',function()
 local g=Game.new(3)
 g.s.tanks.main[1].sex='M'
 g.s.tanks.main[2].sex='M'
 assert(g:move(1,'isolation'))
 assert(g:move(2,'isolation'))
 assert(g:breed())
 eq(g.s.tanks.isolation[1].mate.parent_id,2)
end)
test('filhotes usam a composicao dos dois pais',function()
 local g=Game.new(6)
 g.s.tanks.main={}
 local one=assert(g:addFish('main',1,3,20,nil,'F'))
 local two=assert(g:addFish('main',19,21,20,nil,'F'))
 assert(g:move(one.id,'isolation'))
 assert(g:move(two.id,'isolation'))
 assert(g:breed())
 local mutation=Config.MUTATION
 Config.MUTATION=0
 g:advance(Config.YEAR*4)
 Config.MUTATION=mutation
 assert(#g.s.tanks.main>=1)
 for _,f in ipairs(g.s.tanks.main) do
  eq(f.body,10);eq(f.tail,12)
  eq(f.parent_ids[1],one.id);eq(f.parent_ids[2],two.id)
 end
end)
test('gestacao nasce apos idade superar idade da reproducao mais 3',function()
 local g=Game.new(11)
 assert(g:move(1,'isolation'));assert(g:move(2,'isolation'))
 assert(g:breed())
 eq(g.s.tanks.isolation[1].gestation_end_age,23)
 g:advance(Config.YEAR*3)
 eq(#g.s.tanks.main,2)
 assert(g:setGrowthMinutes(5))
 g:advance(300)
 assert(#g.s.tanks.main>2)
 eq(g.s.tanks.isolation[1].eggs_at,false)
end)
test('capacidade 18 no principal, segundo e vendas',function()
 local g=Game.new(6)
 eq(Config.CAPACITY.main,18)
 eq(Config.CAPACITY.second,18)
 eq(Config.CAPACITY.sale,18)
 for i=5,18 do assert(g:addFish('main',i%21+1,1,0)) end
 eq(#g.s.tanks.main,18)
 assert(not g:addFish('main',1,1,0))
 assert(not g:addFish('main',22,1,0))
end)
test('save v3 migra sem perder peixes ou gestacao',function()
 local g=Game.new(9)
 g:move(1,'isolation');g:move(2,'isolation');assert(g:breed())
 local before=JSON.decode(JSON.encode(g.s));before.version=3
 before.tanks.isolation[1].mate={body={20,20},tail={16,16}}
 before.time=900
 local restore,err=Game.fromTable(before);assert(restore,err)
 eq(restore.s.version,9)
 eq(restore.s.growth_elapsed,300)
 eq(restore.s.tanks.isolation[1].mate.body_index,20)
 eq(restore.s.tanks.isolation[1].mate.tail_index,16)
 eq(restore.s.tanks.isolation[1].id,1)
end)
test('save v4 guarda os segundos parciais do crescimento',function()
 local g=Game.new(9)
 assert(g:setGrowthMinutes(15));g:advance(444)
 local restore,err=Game.fromTable(JSON.decode(JSON.encode(g.s)));assert(restore,err)
 eq(restore.s.growth_elapsed,444)
 eq(restore.s.growth_minutes,15)
 restore:advance(456)
 eq(restore.s.tanks.main[1].age,21)
end)
test('sprites juvenis por especie e indices de 21 formas',function()
 for i=1,21 do
  local q=Atlas.juvenile[i]
  assert(q and q[1]==100 and q[3]==35 and q[4]>0 and q[2]>=0)
  assert(Catalog.basePrice(i,i)>0)
 end
end)
test('ciclos inteiros e fracao nao se perdem em sequencia',function()
 local g=Game.new(99)
 g:advance(607)
 local other=Game.new(99)
 other:advance(300);other:advance(307)
 eq(g.s.year_tick,other.s.year_tick)
 eq(g.s.time,other.s.time)
 eq(g.s.growth_elapsed,other.s.growth_elapsed)
 eq(JSON.encode(g.s.tanks),JSON.encode(other.s.tanks))
end)
print('\nFase 4: '..count..' testes adicionais passaram.')
