package.path='./?.lua;./?/init.lua;'..package.path
local Visual=require('art.dna_visual')
local C=require('art.catalog')
local native=C.get(4,15,4,4)
local p=assert(Visual.parameters(native))
assert(p.nativePalette==4 and p.nativePattern==4)
assert(p.hueShift==0 and p.patternStrength==0)
local variant=C.get(4,15,6,2)
local v=assert(Visual.parameters(variant))
assert(v.hueShift~=0 and v.patternStrength>0)
assert(v.pattern==2)
local same=C.get(4,15,6,2)
assert(Visual.parameters(same).hueShift==v.hueShift)
local nextShape=C.get(7,15,6,2)
assert(Visual.parameters(nextShape).hueShift~=v.hueShift)
local off=assert(Visual.parameters(C.get(1,1,12,1)))
assert(off.hueShift~=0)
assert(not Visual.parameters({body='bad',palette=1,pattern=2}))
